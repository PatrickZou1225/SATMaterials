#!/usr/bin/env node
// Turn the parsed official-sample JSON (data/official-samples/*.json) plus the
// figure manifest (figures.json) into one typed module the app imports.
//
// Usage: node scripts/build-official-samples.mjs
// Writes src/data/officialSamples.ts.

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DATA = new URL('../data/official-samples/', import.meta.url).pathname
const OUT = new URL('../src/data/officialSamples.ts', import.meta.url).pathname

const SLUGS = [
  'boundaries',
  'central-ideas-and-details',
  'command-of-evidence',
  'cross-text-connections',
  'form-structure-and-sense',
  'inferences',
  'rhetorical-synthesis',
  'text-structure-and-purpose',
  'transitions',
  'words-in-context',
]
const DIFFICULTIES = ['Easy', 'Medium', 'Hard']

const figures = JSON.parse(readFileSync(join(DATA, 'figures.json'), 'utf8'))

let seq = 0
const types = []

for (const slug of SLUGS) {
  const data = JSON.parse(readFileSync(join(DATA, `${slug}.json`), 'utf8'))
  const difficulties = {}
  for (const difficulty of DIFFICULTIES) {
    difficulties[difficulty] = (data.difficulties[difficulty] ?? []).map((q) => {
      const figure = figures[q.qid]
      return {
        id: ++seq,
        qid: q.qid,
        passage: figure?.passage ?? q.passage,
        question: q.question,
        options: q.options,
        answer: q.answer,
        rationale: q.rationale,
        underline: q.underline ?? [],
        ...(figure ? { image: figure.image } : {}),
      }
    })
  }
  types.push({ slug, skill: data.skill, domain: data.domain, label: data.label, difficulties })
}

const lit = JSON.stringify
const lines = []
lines.push('// AUTO-GENERATED by scripts/build-official-samples.mjs — do not edit by hand.')
lines.push('// Source: College Board official SAT question-bank PDFs (30 files, 1843 questions).')
lines.push('')
lines.push("import type { MockTestQuestion } from './mockTestQuestions'")
lines.push('')
lines.push("export type OfficialDifficulty = 'Easy' | 'Medium' | 'Hard'")
lines.push('')
lines.push('// Same core shape as a set question, plus the College Board id and the written')
lines.push('// rationale. Figure questions carry an image of the original table or graph;')
lines.push('// their passage has the flattened figure text already stripped.')
lines.push('export interface OfficialQuestion extends MockTestQuestion {')
lines.push('  qid: string')
lines.push('  rationale: string')
lines.push('}')
lines.push('')
lines.push('export interface OfficialType {')
lines.push('  slug: string')
lines.push('  skill: string')
lines.push('  domain: string')
lines.push('  label: string')
lines.push('  difficulties: Record<OfficialDifficulty, OfficialQuestion[]>')
lines.push('}')
lines.push('')
lines.push('export const OFFICIAL_DIFFICULTIES: OfficialDifficulty[] = [' + DIFFICULTIES.map(lit).join(', ') + ']')
lines.push('')
lines.push('export const officialKey = (slug: string, difficulty: OfficialDifficulty, qid: string): string =>')
lines.push("  `official:${slug}-${difficulty.toLowerCase()}-${qid}`")
lines.push('')
lines.push('export const allOfficialTypes: OfficialType[] = [')

for (const type of types) {
  lines.push('  {')
  lines.push(`    slug: ${lit(type.slug)},`)
  lines.push(`    skill: ${lit(type.skill)},`)
  lines.push(`    domain: ${lit(type.domain)},`)
  lines.push(`    label: ${lit(type.label)},`)
  lines.push('    difficulties: {')
  for (const difficulty of DIFFICULTIES) {
    const list = type.difficulties[difficulty]
    if (list.length === 0) { lines.push(`      ${difficulty}: [],`); continue }
    lines.push(`      ${difficulty}: [`)
    for (const q of list) {
      const parts = [
        `id: ${q.id}`,
        `qid: ${lit(q.qid)}`,
        `passage: ${lit(q.passage)}`,
        `question: ${lit(q.question)}`,
        `options: ${lit(q.options)}`,
        `answer: ${q.answer}`,
        `rationale: ${lit(q.rationale)}`,
      ]
      if (q.underline.length) parts.push(`underline: ${lit(q.underline)}`)
      if (q.image) parts.push(`image: ${lit(q.image)}`)
      lines.push(`        { ${parts.join(', ')} },`)
    }
    lines.push('      ],')
  }
  lines.push('    },')
  lines.push('  },')
}

lines.push(']')
lines.push('')

writeFileSync(OUT, lines.join('\n'))

const total = types.reduce((n, t) => n + DIFFICULTIES.reduce((m, d) => m + t.difficulties[d].length, 0), 0)
console.log(`Wrote ${OUT}`)
console.log(`${types.length} types, ${total} questions, ${Object.keys(figures).length} figures`)
