#!/usr/bin/env node
// Generate the answer-key migration for mock-test grading.
//
//   node scripts/generate-answer-key.mjs
//
// The mock-test page grades itself in the browser today, which means the score
// is whatever the client says it is — attempts.sql granted students update on
// correct_count and insert on is_correct. Server-side grading needs the key in
// the database, so this script walks allMockTests and emits the answer_keys
// seed along with the triggers that grade every attempt.
//
// Re-run it whenever sets are added, then apply the regenerated migration.
import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { createServer } from 'vite'

const ROOT = path.resolve(import.meta.dirname, '..')
const OUT = path.join(ROOT, 'supabase', 'migrations', '20260930000000_attempt_grading.sql')

// Load the TS data through Vite so the extensionless imports inside
// mockTestQuestions.ts resolve the same way they do in the app.
const server = await createServer({
  root: ROOT,
  configFile: path.join(ROOT, 'vite.config.ts'),
  server: { middlewareMode: true },
  appType: 'custom',
  logLevel: 'error',
})

let sets
let questionKey
let moduleNumber
try {
  ;({ allMockTests: sets } = await server.ssrLoadModule('/src/data/mockTestQuestions.ts'))
  ;({ questionKey, moduleNumber } = await server.ssrLoadModule('/src/lib/questionBank.ts'))
} finally {
  await server.close()
}

const seen = new Map()
const rows = []
const emptyModules = []

for (const set of sets) {
  set.modules.forEach((mod, index) => {
    const num = moduleNumber(mod.name, index)
    if (mod.questions.length === 0) emptyModules.push(`${set.id} M${num}`)
    for (const q of mod.questions) {
      const key = questionKey(set.id, mod.name, index, q.id)
      if (seen.has(key)) {
        console.error(`Duplicate question key: ${key} (${set.id} M${num} q${q.id}) already used by ${seen.get(key)}`)
        process.exit(1)
      }
      seen.set(key, `${set.id} M${num} q${q.id}`)
      if (!Number.isInteger(q.answer) || q.answer < 0 || q.answer > 3) {
        console.error(`Bad answer for ${key}: ${q.answer}`)
        process.exit(1)
      }
      rows.push([key, set.id, num, q.answer])
    }
  })
}

// Keep the INSERT statements readable and well under any statement size limit.
const CHUNK = 500
const valueChunks = []
for (let i = 0; i < rows.length; i += CHUNK) {
  valueChunks.push(rows
    .slice(i, i + CHUNK)
    .map(([key, setId, num, answer]) => `  ('${key}', '${setId}', ${num}, ${answer})`)
    .join(',\n'))
}

const sql = `-- Server-side grading for mock-test attempts.
--
-- Before this migration the client graded its own run and wrote the result
-- straight into the score columns: 20260926000001_attempts.sql granted
-- authenticated update (correct_count) on attempts and insert (is_correct) on
-- attempt_answers. Any signed-in student could therefore POST a full-marks
-- attempt with a REST call and the teacher's 学习情况 page would show it.
--
-- Grading now happens in the database. The key below is not readable by clients
-- (no policies, no grants), is_correct is derived on write, and both the score
-- and its denominator are computed when the attempt is closed out.
--
-- Generated by scripts/generate-answer-key.mjs — do not edit by hand.
-- ${rows.length} questions from ${sets.length} sets.

create table public.answer_keys (
  question_key text primary key check (question_key ~ '^[a-z0-9_-]+:[a-z0-9_-]+$'),
  set_id text not null,
  module_num integer not null check (module_num > 0),
  correct_answer integer not null check (correct_answer between 0 and 3)
);

create index answer_keys_module_idx on public.answer_keys (set_id, module_num);

alter table public.answer_keys enable row level security;
revoke all on public.answer_keys from anon, authenticated;

insert into public.answer_keys (question_key, set_id, module_num, correct_answer) values
${valueChunks.join(';\n\ninsert into public.answer_keys (question_key, set_id, module_num, correct_answer) values\n')};

-- Grade every answer row on the way in. The client only ever supplies the
-- selected option; is_correct comes from the key. An unknown question key is
-- never correct, so a made-up key cannot earn marks.
create function public.grade_attempt_answer()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  select (ak.correct_answer = new.selected_answer)
    into new.is_correct
  from public.answer_keys ak
  where ak.question_key = new.question_key;

  if not found then
    new.is_correct := false;
  end if;

  return new;
end;
$$;

revoke all on function public.grade_attempt_answer() from public, anon, authenticated;

create trigger attempt_answers_grade
before insert or update on public.attempt_answers
for each row execute function public.grade_attempt_answer();

-- Derive the two numbers the teacher reads. total_questions is the size of the
-- answer key for that module — not what the client claims — so skipping
-- questions lowers the score instead of shrinking the denominator, and
-- correct_count is counted from the graded rows at submit time.
create function public.set_attempt_totals()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  key_total integer;
  graded integer;
begin
  if tg_op = 'INSERT' then
    select count(*) into key_total
    from public.answer_keys ak
    where ak.set_id = new.set_id and ak.module_num = new.module_num;
    -- A module the key does not cover yet still has to satisfy
    -- check (total_questions > 0); it grades as 0 marks.
    new.total_questions := greatest(key_total, 1);
    return new;
  end if;

  if new.status = 'submitted' and old.status is distinct from 'submitted' then
    select count(*) into graded
    from public.attempt_answers aa
    where aa.attempt_id = new.id and aa.is_correct;
    new.correct_count := graded;
    new.submitted_at := coalesce(new.submitted_at, now());
  end if;

  return new;
end;
$$;

revoke all on function public.set_attempt_totals() from public, anon, authenticated;

create trigger attempts_totals
before insert or update on public.attempts
for each row execute function public.set_attempt_totals();

-- Take the score columns away from the client. status/submitted_at stay so the
-- student can still hand in; everything else is the database's business now.
revoke update (correct_count, status, submitted_at) on public.attempts from authenticated;
grant update (status, submitted_at) on public.attempts to authenticated;

revoke insert (student_id, set_id, module_num, total_questions, status, started_at) on public.attempts from authenticated;
grant insert (student_id, set_id, module_num, status, started_at) on public.attempts to authenticated;

revoke insert (attempt_id, question_key, selected_answer, is_correct, answered_at) on public.attempt_answers from authenticated;
grant insert (attempt_id, question_key, selected_answer, answered_at) on public.attempt_answers to authenticated;

revoke update (selected_answer, is_correct, answered_at) on public.attempt_answers from authenticated;
grant update (selected_answer, answered_at) on public.attempt_answers to authenticated;
`

await writeFile(OUT, sql)

console.log(`Wrote ${path.relative(ROOT, OUT)}`)
console.log(`  ${rows.length} answer keys across ${sets.length} sets`)
if (emptyModules.length) console.log(`  modules with no questions yet: ${emptyModules.join(', ')}`)
